"""Варианты написания названия компании.

Зачем: в реестре компания записана как 'ООО "ТД Вектор-2011"', а в новостях
её называют просто «Вектор». Поиск по одному лишь юридическому наименованию
не найдёт ничего, и система честно, но ошибочно отчитается «негатива нет».

Здесь только ДЕТЕРМИНИРОВАННЫЕ варианты, выводимые из реестровой записи.
Установление рыночного бренда (по сайту, товарным знакам) требует
веб-инструментов и делается позднее.
"""

import re

# Организационно-правовые формы: сокращения и полные написания
_LEGAL_FORMS = (
    "ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ",
    "ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
    "НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
    "ЗАКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
    "ОТКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО",
    "АКЦИОНЕРНОЕ ОБЩЕСТВО",
    "ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ",
    "ООО", "ПАО", "НАО", "ЗАО", "ОАО", "АО", "ИП",
    "ГУП", "МУП", "ФГУП", "ФГБУ", "ГБУ", "МБУ",
    "АНО", "НКО", "НП", "ПК", "СПК", "КФХ", "ТСЖ", "ТСН",
)

# Отраслевые приставки: часто есть в уставном названии и отсутствуют в прессе
_PREFIXES = ("ТД", "ТК", "ПКФ", "НПО", "НПП", "НПФ", "ГК", "УК", "СЗ", "СК")

_QUOTES = '"«»„“”\'`'
_QUOTED = re.compile(r"[«\"„](?P<core>[^»\"“]+)[»\"“]")


def _strip_quotes(text: str) -> str:
    return text.strip().strip(_QUOTES).strip()


def _drop_leading(text: str, words: tuple[str, ...]) -> str:
    """Убрать ведущее слово из списка, если оно там есть."""
    upper = text.upper()
    for w in sorted(words, key=len, reverse=True):
        if upper.startswith(w + " ") or upper == w:
            return text[len(w):].strip()
    return text


def name_variants(*sources: str | None) -> list[str]:
    """Собрать варианты написания названия для поиска.

    Принимает любые известные написания: полное с формой, краткое, чистое
    имя без формы, латиницу. Если источник даёт готовые чистые названия,
    они надёжнее выведенных отсечением — поэтому передавать стоит все.

    Порядок значим: от самого точного к самому широкому.

    >>> name_variants('ООО "ТД Вектор-2011"')
    ['ООО "ТД Вектор-2011"', 'ТД Вектор-2011', 'Вектор-2011']
    """
    out: list[str] = []

    def add(value: str) -> None:
        value = value.strip()
        if value and value not in out:
            out.append(value)

    for source in sources:
        if not source:
            continue

        add(source)

        # Ядро в кавычках — самый надёжный источник имени
        match = _QUOTED.search(source)
        core = match.group("core").strip() if match else None
        if core:
            add(core)

        # Без организационно-правовой формы
        without_form = _drop_leading(source, _LEGAL_FORMS)
        add(_strip_quotes(without_form))

        # Дополнительно без отраслевой приставки
        base = core or _strip_quotes(without_form)
        add(_drop_leading(base, _PREFIXES))

    return out
